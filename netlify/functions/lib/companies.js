/**
 * 텍스트(제목+요약)에서 등록된 회사/기관명을 찾아 [{name, sector}, ...] 형태로 반환합니다.
 * 가장 먼저 매칭되는 것이 아니라, 등장한 모든 회사를 찾아 반환하므로
 * 호출부에서 "가장 중심이 되는 회사"를 고르는 로직을 추가로 둘 수 있습니다.
 */
function extractCompanies(text) {
  if (!text) return [];
  const found = [];
  const seen = new Set();
  for (const [name, sector] of Object.entries(COMPANIES)) {
    if (text.includes(name) && !seen.has(name)) {
      found.push({ name, sector });
      seen.add(name);
    }
  }
  return found;
}

module.exports = { COMPANIES, extractCompanies };
