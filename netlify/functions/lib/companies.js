/**
 * 텍스트(제목+요약)에서 등록된 회사/기관명을 찾아 [{name, sector}, ...] 형태로 반환합니다.
 * 짧은 이름이 다른 매칭된 이름의 부분 문자열인 경우(예: "DB생명"이 "KDB생명"에 포함)는
 * 더 구체적인(긴) 이름만 남기고 제외합니다.
 */
function extractCompanies(text) {
  if (!text) return [];
  const found = [];
  const seen = new Set();
  for (const [name, sector] of Object.entries(COMPANIES)) {
    if (text.includes(name) && !seen.has(name)) {
      found.push({ name, sector });
      seen.add(name);
    }
  }
  // "DB생명"처럼 다른 매칭 이름("KDB생명")의 부분 문자열인 항목은 제거
  return found.filter(
    (item) => !found.some((other) => other.name !== item.name && other.name.includes(item.name))
  );
}

module.exports = { COMPANIES, extractCompanies };
